-- Burger Restaurant — SQLite schema: seven tables and four indexes.
--
-- Applied by src/db/index.js each time the database file is opened:
--   db.exec(fs.readFileSync(path.join(__dirname, 'schema.sql'), 'utf8'))
-- and applied again after a close/re-open, so every statement is guarded with
-- IF NOT EXISTS: running this file against a populated database changes nothing
-- and raises nothing. There are no migration files, no version table and no
-- schema-change statements — the table set below is the whole schema.
--
-- Conventions that hold throughout this file:
--   * Primary keys are UUIDv4 TEXT values generated by the repositories with
--     require('node:crypto').randomUUID(). No integer rowid alias and no
--     expression default, so sqlite_master never gains a sqlite_sequence row.
--   * Money is integer cents only — price_cents, unit_price_cents,
--     line_total_cents, total_cents — computed server-side; no floating-point
--     or fixed-point column type appears here.
--   * Timestamps are UTC ISO-8601 TEXT (YYYY-MM-DDTHH:MM:SS.sssZ) filled by the
--     strftime default, so a row written without them still records one; a
--     repository may still supply its own value explicitly.
--   * Connection-level settings such as foreign-key enforcement and journal
--     mode belong to src/db/index.js, which applies them before this file.
--     This file holds table and index definitions only.
--   * Exactly the seven tables below exist — no cart table (the cart is client
--     state), no capacity table and no bookkeeping table. Nothing else is
--     created by this file.

-- ---------------------------------------------------------------------------
-- users: one row per registered account. email is stored lowercased by the
-- repository layer, which is what makes UNIQUE case-insensitive in practice.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
    id            TEXT PRIMARY KEY,
    name          TEXT NOT NULL,
    email         TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    password_salt TEXT NOT NULL,
    created_at    TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
    updated_at    TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);

-- ---------------------------------------------------------------------------
-- auth_tokens: opaque session tokens. Only the SHA-256 hex digest of a token is
-- stored, never the token itself. revoked_at NULL means the token is active.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS auth_tokens (
    id         TEXT PRIMARY KEY,
    user_id    TEXT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash TEXT NOT NULL UNIQUE,
    expires_at TEXT NOT NULL,
    revoked_at TEXT,
    created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);

-- ---------------------------------------------------------------------------
-- categories: menu categories, read in display_order.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS categories (
    id            TEXT PRIMARY KEY,
    name          TEXT NOT NULL,
    slug          TEXT NOT NULL UNIQUE,
    display_order INTEGER NOT NULL
);

-- ---------------------------------------------------------------------------
-- menu_items: items offered per category. price_cents is the authoritative
-- price an order line is copied from at ordering time.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS menu_items (
    id           TEXT PRIMARY KEY,
    category_id  TEXT NOT NULL REFERENCES categories (id),
    name         TEXT NOT NULL,
    description  TEXT NOT NULL,
    price_cents  INTEGER NOT NULL CHECK (price_cents > 0),
    image_url    TEXT,
    is_available INTEGER NOT NULL DEFAULT 1 CHECK (is_available IN (0, 1))
);

-- ---------------------------------------------------------------------------
-- orders: one row per placed order. total_cents is summed from the order's line
-- items server-side, inside the same transaction that writes those lines.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS orders (
    id          TEXT PRIMARY KEY,
    user_id     TEXT NOT NULL REFERENCES users (id),
    status      TEXT NOT NULL DEFAULT 'confirmed'
                CHECK (status IN ('confirmed', 'preparing', 'completed', 'cancelled')),
    total_cents INTEGER NOT NULL CHECK (total_cents >= 0),
    notes       TEXT,
    created_at  TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);

-- ---------------------------------------------------------------------------
-- order_line_items: one row per menu item on an order. unit_price_cents is the
-- price read from menu_items inside the order transaction; line_total_cents is
-- quantity multiplied by that unit price.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS order_line_items (
    id               TEXT PRIMARY KEY,
    order_id         TEXT NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    menu_item_id     TEXT NOT NULL REFERENCES menu_items (id),
    quantity         INTEGER NOT NULL CHECK (quantity > 0),
    unit_price_cents INTEGER NOT NULL CHECK (unit_price_cents > 0),
    line_total_cents INTEGER NOT NULL
);

-- ---------------------------------------------------------------------------
-- reservations: table bookings. reservation_date is YYYY-MM-DD and
-- reservation_time is HH:MM. uq_reservations_user_slot is named so that the
-- reservation service can recognise a duplicate booking for the same user, date
-- and time; the party-size bound is the storage floor for the API's own limit.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS reservations (
    id               TEXT PRIMARY KEY,
    user_id          TEXT NOT NULL REFERENCES users (id),
    reservation_date TEXT NOT NULL,
    reservation_time TEXT NOT NULL,
    party_size       INTEGER NOT NULL CHECK (party_size BETWEEN 1 AND 12),
    status           TEXT NOT NULL DEFAULT 'confirmed'
                     CHECK (status IN ('confirmed', 'cancelled')),
    notes            TEXT,
    created_at       TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
    CONSTRAINT uq_reservations_user_slot
        UNIQUE (user_id, reservation_date, reservation_time)
);

-- ---------------------------------------------------------------------------
-- Indexes: the declared access paths for menu browsing, per-user order history,
-- per-user reservation history and bearer-token lookup.
-- ---------------------------------------------------------------------------
CREATE INDEX IF NOT EXISTS idx_menu_items_category ON menu_items (category_id);
CREATE INDEX IF NOT EXISTS idx_orders_user_date ON orders (user_id, created_at);
CREATE INDEX IF NOT EXISTS idx_reservations_user_date ON reservations (user_id, reservation_date);
CREATE INDEX IF NOT EXISTS idx_auth_tokens_token_hash ON auth_tokens (token_hash);
